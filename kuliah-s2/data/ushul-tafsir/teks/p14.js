"يقول الشنقيطي بعدما ذكر أقوال العلماء في اسم كلب أصحاب الكهف، قال:",
"بعضهم اسمه كذا، وقال بعضهم: اسمه كذا، إلى غير ذلك مما لم نطل به الكلام لعدم فائدته،",
"يقول الشنقيطي: ففي القرآن العظيم أشياء كثيرة لم يبينها الله لنا ولا رسوله ﷺ، ولم يثبت في بيانها شيء، والبحث عنها لا طائل تحته ولا فائدة فيه، وكثيرٌ من المفسرين يطنبونَ في ذكر الأقوال فيها بدون علمٍ ولا جدوى، ونحن نعرض عن مثل ذلك دائمًا، كلونِ كلب أصحاب الكهف واسمهِ، وكالبعضِ الذي ضرب به القتيل من بقرة بني إسرائيل، وكاسم الغلام الذي قتله الخضر، وأنكر عليه موسى قتله، وكخشبِ سفينة نوح من أي شجرٍ هو؟ وكم طول السفينة وعرضها؟ وكم فيها من الطبقات؟ كل هذا لا فائدة فيه ولا في البحث عنه ولا دليل على التحقيق فيه.",
"القاعدة السابعة:",
"حذف المتعلق المعمول فيه يفيد تعميم المعنى المناسب له.",
"يقول كثيرًا ما يأتي في القرآن خصوصًا في خواتيم الآيات أفعالٌ لا تذكر مفعولاتها، وفي هذه الحالة فإن أول ما يدخل في تقدير المفعول هو ما يناسب السياق ثم ما يكون عامًا بعد ذلك.",
"يقول السعدي رحمه الله: وهذه قاعدةٌ مفيدةٌ جدًا متى اعتبرها الإنسان في الآيات القرآنية اكسبته فوائد جليلة.",
"يقول: وذلك أن الفعل وما هو معناه متى قيد بشيءٍ تقيد به.",
"إذا أتى الفعل مقيدًا يتقيد به.",
"المثال الأول:",
"{ارْجِعُوا إِلَىٰ أَبِيكُمْ فَقُولُوا يَا أَبَانَا إِنَّ ابْنَكَ سَرَقَ} [يوسف: ٨١]",
"\"ارْجِعُوا\" فعل أمر متعلق.",
"{ارْجِعُوا إِلَىٰ أَبِيكُمْ}",
"مثال آخر:",
"{وَاسْأَلِ الْقَرْيَةَ الَّتِي كُنَّا فِيهَا} [يوسف: ٨٢]",
"لو قالوا: واسأل فقط، أين متعلق قل",
"لكنه قال: {وَاسْأَلِ الْقَرْيَةَ الَّتِي كُنَّا فِيهَا وَالْعِيرَ الَّتِي أَقْبَلْنَا فِيهَا ۖ وَإِنَّا لَصَادِقُونَ (٨٢)} فالمتعلق هنا قيد هذا المتعلق فيتقيد به.",
"قال فإذا أطلقه الله تعالى وحذف المتعلق كان القصد من ذلك التعميم.",
"يعني إذا جاء الفعل غير مقيد، كان المراد من ذلك أن يظل على عمومه ويكون الحذف هنا أحسن وأفيد كثيرًا، من التصريح بالمتعلقات، وأجمع للمعاني النافعة.",
"ثم ذكر على ذلك ثلاثة أمثلة.",
"المثال الأول:",
"قول الله تعالى في آياتٍ كثيرة: {لَّعَلَّكُمْ تَعْقِلُونَ}",
"ولم يذكر متعلقها فيدل ذلك على أن المراد {لَّعَلَّكُمْ تَعْقِلُونَ} عن الله كلما أرشدكم إليه وكلما علمكموه، وكلما أنزل عليكم من الكتاب والحكمة، العموم لأن لا يوجد متعلق.",
"المثال الثاني:",
"لعلكم تذكر المعنى يكون",
"{لَعَلَّكُمْ تَذَكَّرُونَ} فلا تنسون ولا تغفلون فتكونون دائمًا متيقظين مرهفي الحواس، تحسون كل ما تمرون به من سنن الله وآياته، فتذكرون جميع مصالحكم الدينية والدنيوية العموم.",
"المثال الثالث:",
"فيكون المراد مع عدم ذكر المتعلق",
"{لَعَلَّكُمْ تَتَّقُونَ} جميع ما يجب اتقاؤه من الغفلة والجهل والتقييد وكل ما يحول، أو يحاول عدوكم أن يوقعكم فيه من جميع الذنوب والمعاصي، ويدخل في ذلك ما كان سياق الكلام فيه وهو فردٌ من إفراد هذا المعنى العام.",
"القاعدة الثامنة:",
"إذا ورد تفسير اللفظ بأكثر من معنىً لغويٍ صحيحٍ تحتمله الآية بلا تضاد، فإنه يجوز التفسير بكل هذه المعاني المحتملة على سبيل تنوع الوجوه في التفسير.",
"المقصود أيها الأحباب أنه إذا كان هناك لفظةٌ في القرآن، ولها أكثر من معنى، وهذه المعاني ليست متفقة إنما مختلفة، لكن مع اختلافها غير متضادة.",
"يعني لا يتناقض بعضها مع بعض، والآية تحتمل هذه المعاني جميعًا، فحينئذٍ يجوز أن تفسر الآية بكل هذه المعاني،",
"يكون أولًا: هذه غير متوافقة مختلفة متضادة.",
"هذه المعاني غير متناقضة غير متناقضة.",
"يعني لا ينقضُ القول بأحدها القول بالآخَر، فحينئذٍ يجوز تفسير الآية بها.",
"ومن أمثلة ذلك:",
"قول الله تعالى: {وَالنَّجْمُ وَالشَّجَرُ يَسْجُدَانِ} [الرحمن: ٦]",
