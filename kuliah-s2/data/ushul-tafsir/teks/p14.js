"ولو كان لله في العلم بأي ذلك من إي رضًا أو لم يخلِ عباده من نصب دلالةٍ لهم عليها، يصلون بها إلى معرفة عينها، ليطيعوهُ بعلمهم بها كما فعل ذلك في كل ما العلم به له رضًا سبحانه وتعالى،",
"فالعلم بذلك لا ينفع والجهل لا يضر.",
"ومن الأمثلة على ذلك:",
