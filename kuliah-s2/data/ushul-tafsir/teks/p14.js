"هذا صحيح، ويكون المعنى يعني تفسير الآية ونجم السماء أو ما نجم من نبات الأرض والشجر يسجدان لله تعالى.",
"القاعدة التاسعة والأخيرة:",
"عند تعدد معنى اللفظة فلا بد من احتمال المعنى المختار للفظة، إذ لا يكفي فيه صحة إطلاقه في اللغة.",
"ومعنى هذه القاعدة أن اللفظة القرآنية قد يكون لها أكثر من معنى، فإذا كان للفظة أكثر من معنى والسياق لا يحتمل كل المعاني، إما يحتمل معنىً واحد فيكون هذا المعنى الواحد يكون هو المختار، ولا يكفي لصحة احتمال المعاني الأخرى كونها صحيحةٌ في فقط.",
"ومن الأمثلة على ذلك:",
"ما فسر به أبو عبيدة معمر بن المثنى تثبيت الأقدام،",
"في قول الله تعالى في سورة الأنفال: {إِذْ يُغَشِّيكُمُ النُّعَاسَ أَمَنَةً مِّنْهُ وَيُنَزِّلُ عَلَيْكُم مِّنَ السَّمَاءِ مَاءً لِّيُطَهِّرَكُم بِهِ وَيُذْهِبَ عَنكُمْ رِجْزَ الشَّيْطَانِ وَلِيَرْبِطَ عَلَىٰ قُلُوبِكُمْ وَيُثَبِّتَ بِهِ الْأَقْدَامَ} [الأنفال: ١١]",
"قال أبو عبيدة: مجازهُ يفرغ عليكم صبرًا وينزله عليكم فيثبتونَ لعدوهم، يفرغ عليهم الصبر وينزلهُ عليهم فيثبتونَ لعدوهِم.",
